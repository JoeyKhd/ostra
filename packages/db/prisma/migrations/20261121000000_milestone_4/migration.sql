-- backfill: repo.position (begin)
-- Each project's repos, numbered by creation from 0, as the project page listed them before.
UPDATE "repo" AS r SET "position" = numbered.n
FROM (
  SELECT id, (row_number() OVER (PARTITION BY "projectId" ORDER BY "createdAt", id) - 1)::int AS n FROM "repo"
) AS numbered
WHERE r.id = numbered.id;
