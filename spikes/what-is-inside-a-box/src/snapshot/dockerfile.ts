// The snapshot build (ADR 0038): a snapshot is the environment prepared ahead
// of time, so a box starts in seconds. On `docker` and `kubernetes` it is an
// OCI image, built by a runner. It holds the base image, every repo's checkout
// and the result of the setup script. It NEVER holds a secret.
//
// A secret marked "available during setup" is mounted for the build only (a
// BuildKit secret mount), and the build fails if the secret's value is found
// in the image. This module generates that Dockerfile from the environment,
// and the harness checks the generated form.
//
// ostra owns this format, so the inputs are validated with a strict schema.

import { z } from "zod";

export const repoSchema = z.strictObject({
  /** `owner/name`, the checkout directory under the task root. */
  name: z
    .string()
    .regex(/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/)
    // `COPY repos/<name>` must stay inside the build context.
    .refine((value) => value.split("/").every((part) => part !== "." && part !== ".."), { message: "no . or .. segments" }),
  /** The default-branch commit the snapshot pins. */
  commit: z.string().regex(/^[0-9a-f]{40}$|^[0-9a-f]{64}$/),
});

export const setupSecretSchema = z.strictObject({
  /** The id under which the secret is mounted, e.g. `npm_token`. */
  id: z.string().regex(/^[a-z][a-z0-9_]{0,63}$/),
  /** Where the setup script reads it, e.g. `/run/secrets/npm_token`. */
  mountPath: z.string().regex(/^\/run\/secrets\/[a-z0-9_]+$/),
});

export const snapshotSpecSchema = z.strictObject({
  /** The base image (ADR 0046), by digest so the snapshot is reproducible. */
  baseImage: z.string().regex(/^[^\s@]+@sha256:[0-9a-f]{64}$/),
  repos: z.array(repoSchema).min(1).max(32),
  /** POSIX shell, run as the agent user in the workspace. No secret is embedded here. */
  setupScript: z.string().max(100_000),
  setupSecrets: z.array(setupSecretSchema).max(16).default([]),
  /** The task root in the agent's container. */
  taskRoot: z.string().regex(/^\/[A-Za-z0-9_./-]+$/).default("/task"),
});
export type SnapshotSpec = z.input<typeof snapshotSpecSchema>;

const shJoin = (lines: readonly string[]): string => lines.join(" \\\n    && ");

/**
 * Generates the snapshot Dockerfile. The repo checkouts are added by the
 * runner's build context (the runner clones each repo at its pinned commit and
 * stages it), so no network and no git token is needed in the build itself.
 * Setup secrets are BuildKit secret mounts, never build args or COPYed files.
 */
export const generateSnapshotDockerfile = (input: SnapshotSpec): string => {
  const spec = snapshotSpecSchema.parse(input);
  const workspace = `${spec.taskRoot}/workspace`;
  const lines: string[] = [
    "# syntax=docker/dockerfile:1.7",
    "# Generated by ostra (spike 3). One snapshot per project (ADR 0038).",
    "# Built with rootless BuildKit; secrets are mount-only and never in a layer.",
    `FROM ${spec.baseImage}`,
    "",
    "USER agent",
    `WORKDIR ${workspace}`,
    "",
  ];
  for (const repo of spec.repos) {
    lines.push(`# ${repo.name} @ ${repo.commit}`);
    // The runner stages each repo's checkout under context/repos/<name>.
    lines.push(`COPY --chown=agent:agent repos/${repo.name} ${workspace}/${repo.name.split("/")[1] ?? repo.name}`);
  }
  lines.push("", "COPY --chown=agent:agent setup.sh /tmp/ostra-setup.sh", "");

  const mounts = spec.setupSecrets.map((secret) => `--mount=type=secret,id=${secret.id},target=${secret.mountPath},uid=1000`).join(" ");
  const runPrefix = mounts === "" ? "RUN" : `RUN ${mounts}`;
  lines.push(
    shJoin([
      `${runPrefix} set -eu`,
      "sh /tmp/ostra-setup.sh",
      "rm -f /tmp/ostra-setup.sh",
    ]),
  );
  lines.push("");
  return `${lines.join("\n")}\n`;
};

/**
 * Checks a built image's layers for any setup secret's value (ADR 0038: "The
 * build fails if the secret's value is found in the image"). Given the plain
 * text of each layer's files, returns the ids of secrets found. The harness
 * supplies the layer contents; in production the runner scans the exported
 * image. Never returns the value itself.
 */
export const secretsFoundInLayers = (layerTexts: readonly string[], secretValues: Readonly<Record<string, string>>): string[] => {
  const found = new Set<string>();
  for (const [id, value] of Object.entries(secretValues)) {
    if (value.length < 6) continue;
    for (const text of layerTexts) {
      if (text.includes(value)) {
        found.add(id);
        break;
      }
    }
  }
  return [...found];
};
